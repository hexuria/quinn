//! Makepad `script_mod!` text. The header stays a fixed height so the
//! block the watcher keys on does not move when the view grows.

use quinn_core::{Style, Tag};
use quinn_styles::{parse_classes, AlignSpec, FlowSpec, SizeSpec};

use crate::model::*;
use crate::Shell;

pub fn emit_rust(model: &Model, shell: &Shell) -> String {
    let mut body = String::new();
    body.push_str("        use mod.prelude.widgets.*\n");
    // A missing `mod.state` is an error, not nil. `ok{...}` turns that into nil.
    body.push_str("        if ok{mod.state} == nil {\n");
    body.push_str("            mod.state = {\n");
    for line in seed_lines(model) {
        body.push_str(&format!("                {line}\n"));
    }
    body.push_str("            }\n");
    body.push_str("        }\n");
    body.push_str("        let state = mod.state\n");
    if let Some(signal) = &model.frame {
        body.push_str("        fn quinn_frame() {\n");
        body.push_str(&format!("            state.{signal} += 1\n"));
        body.push_str("            ui.host.render()\n");
        body.push_str("        }\n");
        // `script_eval!` from Rust is a different body. It sees `mod`, not this scope.
        body.push_str("        mod.quinn_frame = quinn_frame\n");
    }
    if model.keyed {
        body.push_str(
            r#"        fn quinn_row_n(id) {
            let key = "k" + id
            let n = state.counts[key]
            if n == nil { return 0 }
            return n
        }
        fn quinn_row_bump(id) {
            let key = "k" + id
            if state.counts[key] == nil {
                state.counts[key] = 1
            } else {
                state.counts[key] = state.counts[key] + 1
            }
        }
"#,
        );
    }
    if has_reverse(&model.nodes) {
        body.push_str(
            r#"        fn quinn_reverse(items) {
            let n = items.len()
            let out = []
            var i = n
            loop {
                if i <= 0 { break }
                i -= 1
                out.push(items[i])
            }
            return out
        }
"#,
        );
    }
    let shows = collect_shows(&model.nodes);
    body.push_str(&emit_show_fns(&model.nodes, &shows));
    for node in &model.nodes {
        if let ViewNode::For {
            fn_name,
            params,
            child,
            ..
        } = node
        {
            body.push_str(&emit_row_fn(fn_name, params, child));
        }
    }
    if model.retain {
        body.push_str(&emit_retain(model));
    }
    let host = host_fields(&model.root_class);
    let mut children = String::new();
    let mut cursor = ShowCursor {
        sites: &shows,
        index: 0,
    };
    // TextInput fires `on_change` with `vm.call`, which has no widget uid, so
    // `ui.host` from that closure cannot see the app host. `on_render` runs on
    // the host view; capturing it lets the input call `root.render()`.
    if has_input(&model.nodes) {
        children.push_str("                                let root = ui\n");
    }
    for node in &model.nodes {
        children.push_str(&emit_node(node, 8, None, &mut cursor));
    }
    let title = shell.title.replace('\\', "\\\\").replace('"', "\\\"");
    body.push_str(&format!(
        r#"        startup() do #(crate::App::script_component(vm)) {{
            ui: Root {{
                on_startup: || {{
                    ui.host.render()
                }}
                main_window := Window {{
                    window.inner_size: vec2({width}, {height})
                    window.title: "{title}"
                    body +: {{
                        host := RoundedView {{
{host}
                            on_render: || {{
{children}                            }}
                        }}
                    }}
                }}
            }}
        }}
"#,
        width = shell.width,
        height = shell.height,
    ));
    format!(
        r#"// Generated by quinn-lower. Do not edit.
// This header is stable so the block token stays on the same line.
use quinn::makepad_widgets::*;

script_mod! {{
{body}}}
"#
    )
}

fn has_input(nodes: &[ViewNode]) -> bool {
    fn el(el: &El) -> bool {
        el.input.is_some() || el.children.iter().any(walk)
    }
    fn walk(node: &ViewNode) -> bool {
        match node {
            ViewNode::El(item) => el(item),
            ViewNode::Show { child, .. } => walk(child),
            ViewNode::For { child, .. } => el(child),
        }
    }
    nodes.iter().any(walk)
}

fn has_reverse(nodes: &[ViewNode]) -> bool {
    fn el(el: &El) -> bool {
        matches!(el.click, Some(Act::Reverse(_)))
            || el.children.iter().any(walk)
    }
    fn walk(node: &ViewNode) -> bool {
        match node {
            ViewNode::El(item) => el(item),
            ViewNode::Show { child, .. } => walk(child),
            ViewNode::For { child, .. } => el(child),
        }
    }
    nodes.iter().any(walk)
}

fn emit_retain(model: &Model) -> String {
    let open = model
        .signals
        .iter()
        .find(|signal| matches!(signal.init, Init::Bool(_)))
        .map(|signal| signal.read.as_str())
        .unwrap_or("open");
    let items = model
        .signals
        .iter()
        .find(|signal| matches!(signal.init, Init::Items(_)))
        .map(|signal| signal.read.as_str())
        .unwrap_or("items");
    let next = model
        .signals
        .iter()
        .find(|signal| signal.read.contains("next"))
        .map(|signal| signal.read.as_str())
        .unwrap_or("next_id");
    let label = model
        .signal(items)
        .and_then(|signal| match &signal.init {
            Init::Items(rows) => rows.first().map(|item| item.label.clone()),
            _ => None,
        })
        .unwrap_or_else(|| "Alpha".into());
    let label = escape_script(&label);
    format!(
        r#"        fn quinn_retain_step(i) {{
            state.{open} = if i % 2 == 0 {{ true }} else {{ false }}
            if state.{open} {{
                let id = state.{next}
                state.{next} = id + 1
                state.{items}.push({{id: id, label: "Item " + id}})
            }} else {{
                if state.{items}.len() > 1 {{
                    state.{items}.pop()
                }}
            }}
            ui.host.render()
        }}
        fn quinn_retain_reset() {{
            state.{open} = false
            state.{items} = [{{id: 1, label: "{label}"}}]
            state.{next} = 2
            ui.host.render()
        }}
        mod.quinn_retain_step = quinn_retain_step
        mod.quinn_retain_reset = quinn_retain_reset
"#
    )
}

fn seed_lines(model: &Model) -> Vec<String> {
    let mut lines = Vec::new();
    for signal in &model.signals {
        lines.push(match &signal.init {
            Init::Int(value) => format!("{}: {value}", signal.read),
            Init::Bool(value) => format!("{}: {value}", signal.read),
            Init::Str(value) => format!("{}: \"{}\"", signal.read, escape_script(value)),
            Init::Items(items) => {
                let rows = items
                    .iter()
                    .map(|item| {
                        format!(
                            "{{id: {}, label: \"{}\"}}",
                            item.id,
                            escape_script(&item.label)
                        )
                    })
                    .collect::<Vec<_>>()
                    .join(", ");
                format!("{}: [{rows}]", signal.read)
            }
        });
    }
    if model.keyed {
        lines.push("counts: {}".into());
    }
    for flag in live_flags(&model.nodes) {
        lines.push(format!("{flag}: 0"));
    }
    lines
}

fn live_flags(nodes: &[ViewNode]) -> Vec<String> {
    let mut out = Vec::new();
    fn walk(node: &ViewNode, out: &mut Vec<String>) {
        match node {
            ViewNode::Show { live_flag, child, .. } => {
                out.push(live_flag.clone());
                walk(child, out);
            }
            ViewNode::El(el) => {
                for child in &el.children {
                    walk(child, out);
                }
            }
            ViewNode::For { .. } => {}
        }
    }
    for node in nodes {
        walk(node, &mut out);
    }
    out
}

fn emit_row_fn(fn_name: &str, params: &[String], child: &El) -> String {
    let mut args = String::from("id");
    for param in params {
        args.push_str(", ");
        args.push_str(param);
    }
    // Row templates in the examples do not contain `<Show>`. A show inside a
    // row would need this cursor positioned at that show's index.
    let sites = Vec::new();
    let mut cursor = ShowCursor {
        sites: &sites,
        index: 0,
    };
    let widget = emit_el(child, Some(fn_name), 3, false, &mut cursor);
    format!("        fn {fn_name}({args}) {{\n{widget}        }}\n")
}

struct ShowSite {
    name: String,
    /// Cursor index just after this show and the shows nested inside it.
    end: usize,
}

struct ShowCursor<'a> {
    sites: &'a [ShowSite],
    index: usize,
}

fn collect_shows(nodes: &[ViewNode]) -> Vec<ShowSite> {
    let mut sites = Vec::new();
    let mut nth = std::collections::HashMap::<String, usize>::new();
    for node in nodes {
        collect_show(node, &mut sites, &mut nth);
    }
    sites
}

fn collect_show(
    node: &ViewNode,
    sites: &mut Vec<ShowSite>,
    nth: &mut std::collections::HashMap<String, usize>,
) {
    match node {
        ViewNode::El(el) => {
            for child in &el.children {
                collect_show(child, sites, nth);
            }
        }
        ViewNode::Show { signal, child, .. } => {
            let n = nth.entry(signal.clone()).or_insert(0);
            *n += 1;
            let name = format!("quinn_show_{signal}_{}", *n);
            let idx = sites.len();
            sites.push(ShowSite { name, end: 0 });
            collect_show(child, sites, nth);
            sites[idx].end = sites.len();
        }
        ViewNode::For { child, .. } => {
            for nested in &child.children {
                collect_show(nested, sites, nth);
            }
        }
    }
}

/// A statement `if` with no widget on both sides unbalances Makepad's script
/// stack (the branch is popped onto the parent). Each show is a function whose
/// `if` calls two functions, one returning the branch widget and one returning
/// `0`, which a view ignores.
fn emit_show_fns(nodes: &[ViewNode], sites: &[ShowSite]) -> String {
    let mut out = String::new();
    let mut cursor = ShowCursor { sites, index: 0 };
    for node in nodes {
        emit_show_fn(node, &mut cursor, &mut out);
    }
    out
}

fn emit_show_fn(node: &ViewNode, cursor: &mut ShowCursor<'_>, out: &mut String) {
    match node {
        ViewNode::El(el) => {
            for child in &el.children {
                emit_show_fn(child, cursor, out);
            }
        }
        ViewNode::Show {
            signal,
            live_flag,
            reset,
            child,
        } => {
            let idx = cursor.index;
            let name = cursor.sites[idx].name.clone();
            cursor.index += 1;
            match &**child {
                ViewNode::El(el) => {
                    for nested in &el.children {
                        emit_show_fn(nested, cursor, out);
                    }
                }
                other => emit_show_fn(other, cursor, out),
            }
            let mut body_cursor = ShowCursor {
                sites: cursor.sites,
                index: idx + 1,
            };
            let body = match &**child {
                ViewNode::El(el) => emit_el(el, None, 3, false, &mut body_cursor),
                other => emit_node(other, 3, None, &mut body_cursor),
            };
            let mut resets = format!("            let was = state.{live_flag}\n");
            resets.push_str(&format!(
                "            state.{live_flag} = if state.{signal} {{ 1 }} else {{ 0 }}\n"
            ));
            for field in reset {
                resets.push_str(&format!(
                    "            state.{field} = if state.{signal} {{ if was != 1 {{ 0 }} else {{ state.{field} }} }} else {{ 0 }}\n"
                ));
            }
            out.push_str(&format!(
                "        fn {name}_on() {{\n{body}        }}\n        fn {name}_off() {{\n            0\n        }}\n        fn {name}() {{\n{resets}            if state.{signal} {{\n                {name}_on()\n            }} else {{\n                {name}_off()\n            }}\n        }}\n"
            ));
        }
        ViewNode::For { child, .. } => {
            for nested in &child.children {
                emit_show_fn(nested, cursor, out);
            }
        }
    }
}

fn emit_node(
    node: &ViewNode,
    indent: usize,
    row_fn: Option<&str>,
    shows: &mut ShowCursor<'_>,
) -> String {
    match node {
        ViewNode::El(el) => emit_el(el, row_fn, indent, true, shows),
        ViewNode::Show { .. } => {
            let pad = " ".repeat(indent * 4);
            let site = &shows.sites[shows.index];
            let name = site.name.clone();
            shows.index = site.end;
            format!("{pad}{name}()\n")
        }
        ViewNode::For {
            items,
            var,
            key_field,
            fn_name,
            params,
            ..
        } => {
            let pad = " ".repeat(indent * 4);
            let mut call = format!("{fn_name}({var}.{key_field}");
            for param in params {
                call.push_str(&format!(", {var}.{param}"));
            }
            call.push(')');
            format!("{pad}for {var} in state.{items} {{\n{pad}    {call}\n{pad}}}\n")
        }
    }
}

fn emit_el(
    el: &El,
    row_fn: Option<&str>,
    indent: usize,
    named: bool,
    shows: &mut ShowCursor<'_>,
) -> String {
    let pad = " ".repeat(indent * 4);
    let widget = widget_name(&el.tag);
    let tag = tag_of(&el.tag);
    let mut style = tag.defaults();
    if !el.class.is_empty() {
        style.merge_from(&parse_classes(&el.class));
    }
    let mut lines = Vec::new();
    if el.value.is_some() || !el.parts.is_empty() {
        lines.push(format!("text: {}", text_expr(el, row_fn)));
    }
    if let Some(placeholder) = &el.placeholder {
        lines.push(format!(
            "empty_text: \"{}\"",
            escape_script(placeholder)
        ));
    }
    if matches!(el.tag.as_str(), "div") {
        let flow = style.flow.unwrap_or(FlowSpec::Column);
        lines.push(flow_line(flow));
        if let Some(gap) = style.gap {
            lines.push(format!("spacing: {}", script_num(gap)));
        }
        if let Some(padding) = uniform_padding(&style) {
            lines.push(format!("padding: {}", script_num(padding)));
        }
        if let Some(align) = align_line(flow, &style) {
            lines.push(align);
        }
    }
    push_control(&mut lines, tag, &style);
    if let Some(signal) = &el.input {
        lines.push(format!(
            "on_change: |text| {{\n{pad}    state.{signal} = text\n{pad}    root.render()\n{pad}}}"
        ));
    }
    if let Some(act) = &el.click {
        let body = emit_act(act, row_fn, &pad);
        let key = if el.input.is_some() {
            "on_change"
        } else {
            "on_click"
        };
        if el.input.is_none() {
            lines.push(format!("{key}: || {{\n{body}{pad}}}"));
        }
    }
    let inner = lines
        .into_iter()
        .map(|line| format!("{pad}    {line}\n"))
        .collect::<String>();
    let mut children = String::new();
    for child in &el.children {
        children.push_str(&emit_node(child, indent + 1, row_fn, shows));
    }
    let head = if named {
        format!("{pad}{} := {widget} {{\n", el.name)
    } else {
        format!("{pad}{widget} {{\n")
    };
    format!("{head}{inner}{children}{pad}}}\n")
}

fn emit_act(act: &Act, row_fn: Option<&str>, pad: &str) -> String {
    let inner = " ".repeat(pad.len() + 4);
    let mut lines = Vec::new();
    match act {
        Act::Inc(signal) => lines.push(format!("state.{signal} += 1")),
        Act::Toggle(signal) => lines.push(format!("state.{signal} = !state.{signal}")),
        Act::Clear(signal) => lines.push(format!("state.{signal} = \"\"")),
        Act::Pop(signal) => lines.push(format!("state.{signal}.pop()")),
        Act::Reverse(signal) => lines.push(format!("state.{signal} = quinn_reverse(state.{signal})")),
        Act::Push { next, items } => {
            lines.push(format!("let id = state.{next}"));
            lines.push(format!("state.{next} = id + 1"));
            lines.push(format!(
                "state.{items}.push({{id: id, label: \"Item \" + id}})"
            ));
        }
        Act::RowInc => {
            let func = row_fn.unwrap_or("quinn_row");
            lines.push(format!("{func}_bump(id)"));
        }
    }
    lines.push("ui.host.render()".into());
    lines
        .into_iter()
        .map(|line| format!("{inner}{line}\n"))
        .collect()
}

fn text_expr(el: &El, row_fn: Option<&str>) -> String {
    if let Some(signal) = &el.value {
        if let Some(func) = row_fn {
            return format!("\"\" + {func}_n(id)");
        }
        return format!("state.{signal}");
    }
    if el.parts.is_empty() {
        return "\"\"".into();
    }
    el.parts
        .iter()
        .map(|part| match part {
            Part::Lit(text) => format!("\"{}\"", escape_script(text)),
            Part::Sig(name) => {
                if row_fn.is_some() {
                    let func = row_fn.unwrap_or("quinn_row");
                    format!("\"\" + {func}_n(id)")
                } else {
                    format!("state.{name}")
                }
            }
            Part::IfBool { signal, yes, no } => format!(
                "if state.{signal} {{ \"{}\" }} else {{ \"{}\" }}",
                escape_script(yes),
                escape_script(no)
            ),
            Part::IfEmpty { signal, empty } => format!(
                "if state.{signal} == \"\" {{ \"{}\" }} else {{ state.{signal} }}",
                escape_script(empty)
            ),
            Part::Param(name) => name.clone(),
        })
        .collect::<Vec<_>>()
        .join(" + ")
}

fn widget_name(tag: &str) -> &'static str {
    match tag {
        "h1" => "H1",
        "h2" => "H2",
        "button" => "Button",
        "input" => "TextInput",
        "div" => "RoundedView",
        _ => "Label",
    }
}

fn tag_of(tag: &str) -> Tag {
    match tag {
        "h1" => Tag::H1,
        "h2" => Tag::H2,
        "button" => Tag::Button,
        "input" => Tag::Input,
        "div" => Tag::Div,
        "p" => Tag::P,
        "label" => Tag::Label,
        _ => Tag::Span,
    }
}

fn host_fields(class: &str) -> String {
    let mut style = Tag::Div.defaults();
    style.merge_from(&parse_classes(class));
    let flow = style.flow.unwrap_or(FlowSpec::Column);
    let mut lines = vec![
        "width: Fill".to_string(),
        "height: Fill".to_string(),
        flow_line(flow),
    ];
    if let Some(gap) = style.gap {
        lines.push(format!("spacing: {}", script_num(gap)));
    }
    if let Some(padding) = uniform_padding(&style) {
        lines.push(format!("padding: {}", script_num(padding)));
    }
    if let Some(align) = align_line(flow, &style) {
        lines.push(align);
    }
    lines.push("show_bg: true".into());
    lines.push("new_batch: true".into());
    let bg = style
        .background
        .map(|color| color.hex_script())
        .unwrap_or_else(|| "#xf4f0e6".into());
    lines.push(format!("draw_bg.color: {bg}"));
    lines
        .into_iter()
        .map(|line| format!("                            {line}\n"))
        .collect()
}

fn push_control(lines: &mut Vec<String>, tag: Tag, style: &Style) {
    match style.width {
        Some(SizeSpec::Fill) => lines.push("width: Fill".into()),
        Some(SizeSpec::Fit) => lines.push("width: Fit".into()),
        Some(SizeSpec::Px(px)) => lines.push(format!("width: {}", script_num(px))),
        None => {}
    }
    match style.height {
        Some(SizeSpec::Fill) => lines.push("height: Fill".into()),
        Some(SizeSpec::Fit) => lines.push("height: Fit".into()),
        Some(SizeSpec::Px(px)) => lines.push(format!("height: {}", script_num(px))),
        None => {}
    }
    if let Some(padding) = uniform_padding(style) {
        if !matches!(
            tag,
            Tag::Div | Tag::H1 | Tag::H2 | Tag::Span | Tag::P | Tag::Label
        ) {
            lines.push(format!("padding: {}", script_num(padding)));
        }
    }
    if matches!(tag, Tag::Button | Tag::Input | Tag::Div) {
        if let Some(color) = style.background {
            let hex = color.hex_script();
            lines.push(format!("draw_bg.color: {hex}"));
            if matches!(tag, Tag::Button) {
                lines.push(format!("draw_bg.color_hover: {hex}"));
                lines.push(format!("draw_bg.color_down: {hex}"));
                lines.push(format!("draw_bg.color_focus: {hex}"));
            }
        }
        if let Some(radius) = style.radius {
            lines.push(format!("draw_bg.border_radius: {}", script_num(radius)));
        }
    }
    if let Some(color) = style.color {
        let hex = color.hex_script();
        lines.push(format!("draw_text.color: {hex}"));
        if matches!(tag, Tag::Button) {
            lines.push(format!("draw_text.color_hover: {hex}"));
            lines.push(format!("draw_text.color_down: {hex}"));
            lines.push(format!("draw_text.color_focus: {hex}"));
        }
    }
    if let Some(size) = style.font_size {
        lines.push(format!("draw_text.text_style.font_size: {size}"));
    }
    if let Some(width) = style.border_width {
        if matches!(tag, Tag::Input | Tag::Div) {
            lines.push(format!("draw_bg.border_size: {}", script_num(width)));
        }
    }
    if let Some(color) = style.border_color {
        if matches!(tag, Tag::Input | Tag::Div) {
            lines.push(format!("draw_bg.border_color: {}", color.hex_script()));
        }
    }
}

fn uniform_padding(style: &Style) -> Option<f64> {
    let (left, top, right, bottom) = style.padding.resolve();
    if style.padding.left.is_none()
        && style.padding.top.is_none()
        && style.padding.right.is_none()
        && style.padding.bottom.is_none()
    {
        return None;
    }
    if left == top && top == right && right == bottom {
        Some(left)
    } else {
        None
    }
}

fn flow_line(flow: FlowSpec) -> String {
    match flow {
        FlowSpec::Column => "flow: Down".into(),
        FlowSpec::Row => "flow: Right".into(),
    }
}

fn align_line(flow: FlowSpec, style: &Style) -> Option<String> {
    if style.main_align.is_none() && style.cross_align.is_none() {
        return None;
    }
    let frac = |align: Option<AlignSpec>| align.map(AlignSpec::fraction).unwrap_or(0.0);
    let (x, y) = match flow {
        FlowSpec::Column => (frac(style.cross_align), frac(style.main_align)),
        FlowSpec::Row => (frac(style.main_align), frac(style.cross_align)),
    };
    Some(format!(
        "align: Align{{x: {} y: {}}}",
        script_num(x),
        script_num(y)
    ))
}

fn escape_script(text: &str) -> String {
    text.replace('\\', "\\\\").replace('"', "\\\"")
}

fn script_num(value: f64) -> String {
    if value.fract() == 0.0 && value.abs() < 1e12 {
        format!("{}.", value as i64)
    } else {
        format!("{value}")
    }
}
