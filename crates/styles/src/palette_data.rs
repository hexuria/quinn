//! Tailwind v3 hues (50–950) and Apple system colors.
//!
//! Apple values are the sRGB colors published for the system palette
//! (light and dark). Semantic names flip when [`set_dark`] is set, which
//! `parse_classes_in` does for a `dark:` variant. Tailwind hues do not flip.

use std::cell::Cell;

use super::Rgba;

thread_local! {
    static PALETTE_DARK: Cell<bool> = const { Cell::new(false) };
}

pub fn set_dark(dark: bool) {
    PALETTE_DARK.with(|cell| cell.set(dark));
}

pub fn is_dark() -> bool {
    PALETTE_DARK.with(|cell| cell.get())
}

pub fn color(name: &str) -> Option<Rgba> {
    if let Some(color) = apple(name, is_dark()) {
        return Some(color);
    }
    tailwind(name)
}

fn rgba(r: u8, g: u8, b: u8, a: u8) -> Rgba {
    Rgba { r, g, b, a }
}

